def pattern(aliases):
    alternatives = []
    for alias in sorted(aliases, key=len, reverse=True):
        # A wing code must end here; a building name may precede a room's block.
        end = r"(?![A-Z])" if alias[-1].isascii() else r"(?=$|[^A-Z]|[A-Z](?:[0-9楼栋座]|$))"
        alternatives.append(re.escape(alias) + end)
    return "(?:" + "|".join(alternatives) + ")"


def palette():
    buildings = []
    for name, x, y, aliases in BUILDINGS:
        area, cx, cy, hue = min(AREAS, key=lambda area: (x - area[1]) ** 2 + (y - area[2]) ** 2)
        hue += 10 * math.tanh((cy - y) / 350) + 6 * math.tanh((cx - x) / 350)
        buildings.append({"name": name, "area": area, "point": [x, y], "aliases": aliases, "pattern": pattern(aliases), **colors(hue)})
    return {"neutral": colors(0, 0), "buildings": buildings}


def dart_colors(values):
    return "(fill: 0x%08X, text: 0x%08X, accent: 0x%08X)" % tuple(values)


def generate():
    table = palette()
    lines = [
        "// Generated by python3 tool/building_palette.py. Do not edit.",
        "part of 'building_palette.dart';", "",
        "const unknownBuildingPalette = BuildingPalette(",
        "  name: '地点待定',",
        f"  light: {dart_colors(table['neutral']['light'])},",
        f"  dark: {dart_colors(table['neutral']['dark'])},", ");", "",
        "const _buildingData = [",
    ]
    for building in table["buildings"]:
        lines.extend([
            "  (", f"    r'{building['pattern']}',", "    BuildingPalette(",
            f"      name: '{building['name']}',",
            f"      area: CampusArea.{building['area']},",
            f"      light: {dart_colors(building['light'])},",
            f"      dark: {dart_colors(building['dark'])},", "    ),", "  ),",
        ])
    lines.append("];")
    Path("lib/schedule/building_palette.g.dart").write_text("\n".join(lines) + "\n", encoding="utf-8")
    asset = Path("android/app/src/main/assets/building_palette.json")
    asset.parent.mkdir(parents=True, exist_ok=True)
    asset.write_text(
        '{\n  "neutral": ' + json.dumps(table["neutral"]) + ',\n  "buildings": [\n'
        + ",\n".join("    " + json.dumps(row, ensure_ascii=False) for row in table["buildings"])
        + "\n  ]\n}\n", encoding="utf-8",
    )


if __name__ == "__main__":
    generate()
